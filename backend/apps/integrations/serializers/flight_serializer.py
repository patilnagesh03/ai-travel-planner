"""
Serializers for the deterministic flight link response.

The links are generated by `FlightService`; nothing here talks to a
provider. `URLField` is still used so a malformed URL is caught before it
reaches the browser.
"""

from rest_framework import serializers


class FlightLinkSerializer(serializers.Serializer):

    provider = serializers.CharField(read_only=True)
    label = serializers.CharField(read_only=True)
    url = serializers.URLField(read_only=True)


class FlightLinksSerializer(serializers.Serializer):

    origin = serializers.CharField(read_only=True)
    destination = serializers.CharField(read_only=True)
    start_date = serializers.DateField(read_only=True)
    end_date = serializers.DateField(read_only=True)
    travelers = serializers.IntegerField(read_only=True)
    disclaimer = serializers.CharField(read_only=True)
    links = FlightLinkSerializer(many=True, read_only=True)


__all__ = [
    "FlightLinkSerializer",
    "FlightLinksSerializer",
]
